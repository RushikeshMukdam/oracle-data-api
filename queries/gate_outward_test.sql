SELECT
    h.GATE_ENTRY_NUMBER,
    h.VEHICLE_NUMBER,
    h.ENTRY_DATE,
    82 AS LOCATION_ID,
    h.TRANSPORTER_NAME,
    l.CUSTOMER,
    l.EX_INVOICE_NO,
    l.EX_INVOICE_DATE,
    l.FLAG
FROM APPS.XXHHL_GATE_ENTRY_OUT_HEADER h
JOIN APPS.XXHHL_GATE_ENTRY_OUT_LINES l
    ON l.GATE_ENTRY_NUMBER = h.GATE_ENTRY_NUMBER
WHERE h.ENTRY_DATE >= DATE '2026-08-01'
  AND h.ENTRY_DATE <  DATE '2026-09-01'
ORDER BY
    h.GATE_ENTRY_NUMBER,
    l.EX_INVOICE_DATE
