SELECT
    h.GATE_ENTRY_NUMBER,
    h.VEHICLE_NUMBER,
    h.ENTRY_DATE,
    82 AS LOCATION_ID,
    h.TRANSPORTER_NAME,
    l.CHALLAN,
    l.CHALLAN_DATE,
    l.GRN,
    l.VENDOR_NAME,
    l.STATUS,
    l.CUST_VEN_FLAG,
    l.CHALLAN_WAY_FLAG,
    rsh.RECEIPT_NUM
FROM APPS.XXHHL_GATE_ENTRY_IN_HEADER h
JOIN APPS.XXHHL_GATE_ENTRY_IN_LINES l
    ON l.GATE_ENTRY_NUMBER = h.GATE_ENTRY_NUMBER
LEFT JOIN APPS.RCV_SHIPMENT_HEADERS rsh
    ON TRIM(TO_CHAR(rsh.RECEIPT_NUM)) = TRIM(l.GRN)
LEFT JOIN (
    SELECT
        SHIPMENT_HEADER_ID,
        TRANSACTION_TYPE,
        TRANSACTION_DATE,
        ROW_NUMBER() OVER (
            PARTITION BY SHIPMENT_HEADER_ID
            ORDER BY TRANSACTION_DATE DESC, TRANSACTION_ID DESC
        ) AS RN
    FROM APPS.RCV_TRANSACTIONS
) rt
    ON rt.SHIPMENT_HEADER_ID = rsh.SHIPMENT_HEADER_ID
   AND rt.RN = 1
WHERE h.ENTRY_DATE >= DATE '2026-07-01'
  AND h.ENTRY_DATE < DATE '2026-08-01'
  AND l.STATUS = 'Active'
  AND l.CHALLAN_WAY_FLAG IN ('3 Way', 'N/A')
ORDER BY
    h.GATE_ENTRY_NUMBER,
    l.CHALLAN_DATE,
    l.GRN
